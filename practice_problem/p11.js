// ### Q11. Custom useFetch Hook

// Build a custom `useFetch` hook that handles data, loading, and error states.

// ## ১. সহজ ভাষায় প্রশ্নটি কী?

// আমাদের এমন একটি টুল বা ফাংশন (যেটিকে রিয়্যাক্টে **Custom Hook** বলা হয়) বানাতে হবে, যার নাম হবে `useFetch`। এটার কাজ হলো ইন্টারনেট থেকে (কোনো API বা URL ব্যবহার করে) ডেটা টেনে আনা।

// ডেটা আনার সময় সাধারণত তিনটি অবস্থা বা স্টেট তৈরি হয়, আমাদের হুকটি এই তিনটি জিনিসই ট্র্যাক করবে:

// 1. **data:** ডেটা ঠিকঠাক এসেছে কিনা।
// 2. **loading:** ডেটা এখনো ইন্টারনেট থেকে লোড হচ্ছে কিনা।
// 3. **error:** ডেটা আনতে গিয়ে কোনো ভুল বা সমস্যা হয়েছে কিনা।

// ---

// ## ২. JavaScript/React Solution


import { useState, useEffect } from 'react';

function useFetch(url) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchData = async () => {
      try {
        setLoading(true); // ডেটা লোড হওয়া শুরু হলো
        const response = await fetch(url);
        
        if (!response.ok) {
          throw new Error('ডেটা আনতে সমস্যা হয়েছে!');
        }
        
        const result = await response.json();
        setData(result); // ডেটা সফলভাবে পাওয়া গেল
      } catch (err) {
        setError(err.message); // কোনো ভুল হলে তা ধরা পড়লো
      } finally {
        setLoading(false); // কাজ শেষ, তাই লোডিং বন্ধ
      }
    };

    fetchData();
  }, [url]); // URL পরিবর্তন হলেই কেবল এটি আবার চলবে

  return { data, loading, error };
}

export default useFetch;

