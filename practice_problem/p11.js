// ## ৩. প্রতিটি লাইনের সহজ ব্যাখ্যা

// * **`import { useState, useEffect } from 'react';`** রিয়্যাক্ট থেকে স্টেটের হিসাব রাখার জন্য `useState` এবং ইন্টারনেটের সাথে যোগাযোগ করার জন্য `useEffect` ধার করে নিয়ে আসলাম।
// * **`function useFetch(url) { ... }`** `useFetch` নামে একটি ফাংশন তৈরি করলাম, যা ইনপুট হিসেবে একটি লিংক বা `url` নেবে।
// * **`const [data, setData] = useState(null);`** ইন্টারনেট থেকে যে ডেটা আসবে, তা জমা রাখার জন্য একটি বাক্স (স্টেট) বানালাম। শুরুতে এটি খালি (`null`) থাকবে।
// * **`const [loading, setLoading] = useState(true);`** কাজটি প্রসেস হচ্ছে কিনা তা বোঝার জন্য এই বাক্স। শুরুতে যেহেতু ডেটা লোড হওয়া শুরু হবে, তাই এটি `true` করে রাখলাম।
// * **`const [error, setError] = useState(null);`** যদি কোনো কারণে ডেটা না আসে বা ইন্টারনেট কানেকশন চলে যায়, সেই ভুলটি মনে রাখার জন্য এই বাক্স। শুরুতে কোনো ভুল নেই, তাই এটি `null`।
// * **`useEffect(() => { ... }, [url]);`** এই অংশটি রিয়্যাক্টকে বলে—"যখনই এই হুকটি চালু হবে কিংবা `url` পরিবর্তন হবে, তখনই ভেতরের কোডটুকু রান করো।"
// * **`const fetchData = async () => { ... }`** ডেটা টেনে আনার জন্য একটি স্পেশাল অ্যাসিনক্রোনাস (async) ফাংশন তৈরি করলাম, যা ব্যাকগ্রাউন্ডে কাজ করতে পারে।
// * **`try { ... } catch (err) { ... } finally { ... }`** এটি একটি সেফটি নেট। `try` এর ভেতর আমরা ডেটা আনার চেষ্টা করব, কোনো ভুল হলে তা `catch` ব্লকে গিয়ে ধরা পড়বে, আর ভালো-মন্দ যাই হোক না কেন, শেষে `finally` ব্লকটি চলবেই।
// * **`const response = await fetch(url);`** `fetch` দিয়ে আমরা লিংকে রিকোয়েস্ট পাঠালাম এবং উত্তরের জন্য অপেক্ষা (`await`) করলাম।
// * **`const result = await response.json();`** অনলাইন থেকে আসা কাঁচা ডেটাকে জাভাস্ক্রিপ্টের পড়ার উপযোগী (JSON) ফরম্যাটে রূপান্তর করলাম।
// * **`setData(result);`** এবং **`setError(err.message);`** সব ঠিক থাকলে ডেটা বক্সে রেজাল্ট রাখলাম, আর ভুল হলে এরর বক্সে ভুলের মেসেজটি রেখে দিলাম।
// * **`setLoading(false);`** কাজ তো শেষ (হয় ডেটা এসেছে, না হয় এরর এসেছে), তাই লোডিং স্টেটটি বন্ধ (`false`) করে দিলাম।
// * **`return { data, loading, error };`** সবশেষে অন্য যেকোনো ফাইলে ব্যবহারের জন্য এই তিনটি প্রয়োজনীয় জিনিস একসাথে ফেরত (return) পাঠিয়ে দিলাম।

