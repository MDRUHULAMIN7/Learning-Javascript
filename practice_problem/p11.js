// ## ৪. কেন এই Approach কাজ করছে?

// এই অ্যাপ্রোচটি চমৎকারভাবে কাজ করার মূল কারণ হলো রিয়্যাক্টের **স্টেট ম্যানেজমেন্ট**।

// আমরা যখনই `setData`, `setLoading` বা `setError` ব্যবহার করে ভেতরের মান পরিবর্তন করছি, রিয়্যাক্ট সাথে সাথে পুরো অ্যাপ্লিকেশনটিকে নতুন তথ্য দিয়ে স্ক্রিনে আপডেট করে দিচ্ছে। এছাড়া `useEffect` ব্যবহার করায় প্রতি সেকেন্ডে বা অপ্রয়োজনে বারবার ইন্টারনেটে রিকোয়েস্ট যাচ্ছে না, কেবল `url` পরিবর্তন হলেই নতুন করে ডেটা ফেচ হচ্ছে। ফলে আমাদের কোডটি যেমন পারফেক্ট, তেমনই ফাস্ট থাকছে!