// ### Q12. Custom useDebounce Hook

// Implement a custom `useDebounce` hook for a search input field.

// ## ১. সহজ ভাষায় প্রশ্নটি কী?

// ধরে নাও, তোমার একটি সার্চ বক্স আছে। ইউজার সেখানে "JavaScript" লিখতে চায়। ইউজার যখন প্রতিটা অক্ষর টাইপ করবে (J, a, v, a...), প্রতিবারই যদি ব্যাকএন্ড বা API-তে রিকোয়েস্ট পাঠানো হয়, তবে সার্ভারের ওপর প্রচুর চাপ পড়বে এবং অ্যাপটি স্লো হয়ে যাবে।

// **ডিবান্সিং (Debouncing)** হলো এমন একটি ট্রিক বা কৌশল, যা ইউজারকে মনের আনন্দে টাইপ করতে দেয় এবং টাইপিং শেষ করে ইউজার যখন একটুখানি বিরতি নেয় (যেমন: ৫০০ মিলিসেকেন্ড বা আধা সেকেন্ড), ঠিক তখনই কেবল ফাইনাল সার্চ বা কাজটা সম্পন্ন করে। আমাদের এই কাজের জন্যই একটি কাস্টম হুক বানাতে হবে।

// ---

// ## ২. JavaScript/React Solution


import { useState, useEffect } from 'react';

function useDebounce(value, delay) {
  // ডিবান্সড ভ্যালু জমা রাখার জন্য একটি স্টেট
  const [debouncedValue, setDebouncedValue] = useState(value);

  useEffect(() => {
    // একটি নির্দিষ্ট সময় (delay) পর স্টেট আপডেট করার জন্য টাইমার সেট করলাম
    const handler = setTimeout(() => {
      setDebouncedValue(value);
    }, delay);

    // ক্লিনআপ ফাংশন: নতুন করে টাইপ করলে আগের টাইমারটি বাতিল করে দেবে
    return () => {
      clearTimeout(handler);
    };
  }, [value, delay]); // ভ্যালু বা ডিলের সময় পরিবর্তন হলে এটি আবার চলবে

  return debouncedValue;
}

export default useDebounce;


// ## ৩. প্রতিটি লাইনের সহজ ব্যাখ্যা

// * **`function useDebounce(value, delay) { ... }`** আমরা `useDebounce` নামে একটি ফাংশন তৈরি করলাম, যা ইনপুট হিসেবে একটি `value` (যেমন সার্চ বক্সের লেখা) এবং একটি `delay` (কতক্ষণ অপেক্ষা করতে হবে, মিলিসেকেন্ডে) নেবে।
// * **`const [debouncedValue, setDebouncedValue] = useState(value);`** ডিবান্স হওয়ার পর ফাইনাল যে মানটি পাবো, তা ধরে রাখার জন্য একটি স্টেট তৈরি করলাম। শুরুতে এর মান হবে ইউজারের দেওয়া মূল ভ্যালুটিই।
// * **`useEffect(() => { ... }, [value, delay]);`** যখনই ইউজার সার্চ বক্সে নতুন কিছু টাইপ করবে (`value` পরিবর্তন হবে) অথবা টাইম বা `delay` পরিবর্তন হবে, তখনই এই ইফেক্টটি চালু হবে।
// * **`const handler = setTimeout(() => { ... }, delay);`** আমরা জাভা‌স্ক্রিপ্টের `setTimeout` ব্যবহার করে একটি টাইমার বা ঘড়ি চালু করলাম। এই ঘড়িটি নির্দিষ্ট সময় (যেমন ৫০০ মিলিসেকেন্ড) অপেক্ষা করবে এবং সময় শেষ হলে ভেতরের `setDebouncedValue(value)` কোডটি রান করে স্টেট আপডেট করে দেবে।
// * **`return () => { clearTimeout(handler); };`** এটি হলো এই হুকের সবচেয়ে গুরুত্বপূর্ণ অংশ, যাকে **Cleanup Function** বলে। ইউজার যদি ঘড়ির সময় শেষ হওয়ার আগেই (যেমন ৫০০ মিলিসেকেন্ড হওয়ার আগেই) আরেকটি নতুন অক্ষর টাইপ করে ফেলে, তবে এই লাইনটি আগের সেট করা টাইমার বা ঘড়িটি ভেঙে (বাতিল করে) দেয়।
// * **`return debouncedValue;`** সবশেষে, ডিবান্স হওয়া বা স্থির হওয়া ভ্যালুটি আমরা রিটার্ন করে দিচ্ছি, যা দিয়ে সহজেই API কল করা যাবে।

